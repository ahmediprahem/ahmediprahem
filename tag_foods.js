function role(f) {
  const n = f.n, g = f.g;
  if (g === 0) return has(n, /خبز|توست|رغيف|عيش|صامولي|تميس/) ? 'bread' : has(n, /شوفان|حبوب الإفطار|موسلي|جرانولا|بليلة/) ? 'cereal' : has(n, /بطاط|ذرة|بازيلا/) ? 'tuber' : has(n, /بوشار|كراكرز|rice cake|شرائح الأرز|بسكوت|كيك/) ? 'snk' : 'grain';
  if (g === 1) return 'leg';
  if (g >= 2 && g <= 5) return has(n, /^(بيضة|بياض بيض|بيض )/) ? 'egg' : has(n, /زبدة الفول/) ? 'nutb' : has(n, /جبن|قريش|ريكوتا|لبنة|موزاريلا|شيدر|حلوم|جبنة رومي|دمياطي/) ? 'cheese' : has(n, /نقانق|سجق|مرتديلا|سلامي|بسطرم|برجر|مقدد|شرائح ديك/) ? 'proc' : has(n, /سمك|تونة|سلمون|سردين|رنجة|روبيان|جمبري|محار|بلطي|بوري|كنعد|هامور/) ? 'fish' : has(n, /توفو/) ? 'tofu' : 'meat';
  if (g >= 6 && g <= 8) return 'dairy';
  if (g === 9) return 'veg';
  if (g === 10) return has(n, /عصير|صلصة التفاح/) ? 'juice' : 'fruit';
  if (g === 11) return has(n, /لوز|جوز|فول سوداني|فستق|كاجو|مكسرات|بذور|سمسم|البقان/) ? 'nuts' : has(n, /زيتون/) && !has(n, /زيت زيتون/) ? 'olive' : has(n, /أفوكادو/) ? 'avo' : has(n, /طحينة/) ? 'tahini' : has(n, /زيت|سمن|زبدة/) && !has(n, /زبدة الفول/) ? 'oil' : 'spread';
  return 'sweet';
}
const COST3 = /سلمون|روبيان|جمبري|خروف|غنم|عجل|هامور|كنعد|حاشي|لوز|جوز|كاجو|فستق|البقان|أفوكادو|كينوا|توت|كيوي|يوناني|التونة طازج|ديك رومي|أناناس|مانجو|شيدر|موزاريلا|ريكوتا/;
