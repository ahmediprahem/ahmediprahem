def main(src):
    idx = json.load(open(os.path.join(OUT, 'index.json'), encoding='utf-8'))
    blob = json.loads(gzip.decompress(open(os.path.join(OUT, 'plans.json.gz'), 'rb').read()).decode('utf-8'))
    idx['plans'] = [e for e in idx['plans'] if e['f'] != FK]
    for k in [k for k, v in list(blob['plans'].items()) if k.startswith('Deficit_EG_LowGI-')]: del blob['plans'][k]
    new = 0
    for dp, dn, fns in os.walk(src):
        dn.sort()
        for fn in sorted(fns):
            if not fn.endswith('.docx'): continue
            m = re.match(r'Deficit_EG_LowGI-(\w+)_(\d+)kcal', fn)
            if not m: continue
            fo, lvl = TIERS[m.group(1)][0], int(m.group(2)); d = I.parse(os.path.join(dp, fn))
            assert len(d['days']) == 7 and all(len(y['meals']) == 5 for y in d['days']), fn
            ks = [y['kcal'] for y in d['days'] if y['kcal']]; avg = round(sum(ks) / len(ks)) if ks else lvl
            e = {'i': os.path.splitext(fn)[0], 'f': FK, 'l': lvl, 'fo': fo, 'k': avg}
            if ks and max(ks) - min(ks) > 30: e['kr'] = [min(ks), max(ks)]
            idx['plans'].append(e)
            sh = lambda o: blob['shared'].setdefault(sha(o), o) is not None and sha(o)
            blob['plans'][e['i']] = {'days': [{'t': y['t'], 'k': y['kcal'], 'm': [[mm['n'], mm['it'], mm.get('g') or mm.get('m') or {}] for mm in y['meals'] if mm['it']], 'tp': y['tips']} for y in d['days']],
                                     'subs': sh(d['subs']), 'ex': d['ex'], 'secs': sh(d['secs']), 'title': d.get('title') or ''}
            new += 1
    idx['fams'][FK] = FAM; blob['guides'][FK] = {'spec': spec(), 'client': {}}
    idx['plans'].sort(key=lambda e: (e['f'], e.get('sb') or '', e.get('sx') or '', str(e.get('ag')), e.get('ac') or '', e.get('l') or 0, e.get('wk') or 0, e.get('fo') or '', e.get('lc') or 0, e['i']))
    json.dump(idx, open(os.path.join(OUT, 'index.json'), 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
    raw = json.dumps(blob, ensure_ascii=False, separators=(',', ':')).encode('utf-8')
    with open(os.path.join(OUT, 'plans.json.gz'), 'wb') as f: f.write(gzip.compress(raw, 9, mtime=0))
    print('أُضيف', new, 'نظاماً | العائلات', len(idx['fams']), '| الخطط', len(idx['plans']), '| gz', os.path.getsize(os.path.join(OUT, 'plans.json.gz')) // 1024, 'KB')

if __name__ == '__main__': main(sys.argv[1])
