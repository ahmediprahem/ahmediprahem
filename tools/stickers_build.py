def cut(k):
    s, x0, y0, x1, y1 = BOX[k]; src = Image.open(SRC[s]).convert('RGB')
    if s == 'c': x0, y0, x1, y1 = x0 - 6, y0 - 6, x1 + 6, y1 + 6
    im = src.crop((x0, y0, x1, y1)); mn = np.array(im).astype(int).min(2)
    if s == 'a':
        lab, n = nd.label(mn > 232); edge = set(np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]]))) - {0}
        st = ~np.isin(lab, list(edge)); st = nd.binary_dilation(st, iterations=3); st = nd.binary_opening(st, iterations=1)
    else:
        white = nd.binary_dilation(mn >= 236, iterations=2); lab, n = nd.label(~white); edge = set(np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]]))) - {0}
        st = ~np.isin(lab, list(edge)); st = nd.binary_fill_holes(st); st = nd.binary_opening(st, iterations=2)
    st = nd.binary_fill_holes(st); L, m = nd.label(st); sz = nd.sum(st, L, range(1, m + 1)); st = L == (1 + int(np.argmax(sz)))
    if s == 'c': st = nd.binary_erosion(st, iterations=1)
    al = Image.fromarray((st * 255).astype('uint8')).filter(ImageFilter.GaussianBlur(0.8)); out = im.convert('RGBA'); out.putalpha(al)
    return out.crop(out.getbbox())

def bubble(im, fx, i):
    K = 3; im = im.resize((im.width * K, im.height * K), Image.LANCZOS); W, Hh = im.size
    pad = int(Hh * fx['pad'])
    if pad: c = Image.new('RGBA', (W, Hh + pad), (0, 0, 0, 0)); c.paste(im, (0, pad), im); im = c; Hh += pad
    x0, y0, x1, y1 = fx['r']; base = Hh - pad
    box = [x0 * W, y0 * base + (0 if fx['pad'] and y0 == 0 else pad), x1 * W, y1 * base + pad]
    if fx['pad'] and y0 == 0: box[1] = 0
    lines = fx['t'].split('\n'); bw, bh = box[2] - box[0], box[3] - box[1]
    size = max(int(bh / len(lines) * .72), int(W * .12))
    while True:
        f = ImageFont.truetype(FONT, size); ws = [f.getbbox(l, direction='rtl', language='ar') for l in lines]
        tw = max(b[2] - b[0] for b in ws); th = int(size * 1.25) * len(lines)
        if tw < max(bw * .92, W * .62) or size < 20: break
        size -= 2
    d = ImageDraw.Draw(im); cx, cy = (box[0] + box[2]) / 2, (box[1] + box[3]) / 2
    rw, rh = max(bw, tw + size * .9), max(bh, th + size * .5); r = [cx - rw / 2, cy - rh / 2, cx + rw / 2, cy + rh / 2]
    r = [max(2, r[0]), max(2, r[1]), min(W - 2, r[2]), min(Hh - 2, r[3])]
    d.rounded_rectangle([r[0] - 9, r[1] - 9, r[2] + 9, r[3] + 9], radius=int(rh / 2.2), fill=(255, 255, 255, 255))
    d.rounded_rectangle(r, radius=int(rh / 2.6), fill=FILLS[i % len(FILLS)], outline=(214, 222, 238), width=3)
    y = cy - th / 2
    for l in lines:
        b = f.getbbox(l, direction='rtl', language='ar'); d.text((cx - (b[2] - b[0]) / 2 - b[0], y + (size * 1.25 - (b[3] + b[1])) / 2), l, font=f, fill=(29, 42, 91), direction='rtl', language='ar'); y += size * 1.25
    return im

def main():
    cache, out, prev = {}, {}, []
    for i, (sid, src, side, label, fx) in enumerate(ST):
        if src not in cache: cache[src] = cut(src)
        im = cache[src].copy(); im = bubble(im, fx, i) if fx else im.resize((im.width * 3, im.height * 3), Image.LANCZOS)
        im.thumbnail((200, 200), Image.LANCZOS); b = io.BytesIO(); im.save(b, 'WEBP', quality=72, method=6)
        out[sid] = [side, label, 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()]; prev.append((sid, im))
    js = '// مولَّد بـ tools/stickers_build.py — لا تعدّله يدوياً. ملصقات المحادثة: [الجهة d/c، النص، الصورة]\n(function (r) { r.HXST = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + '; })(typeof self !== \'undefined\' ? self : this);\n'
    open(os.path.join(H, 'src', 'stickers.js'), 'w', encoding='utf-8').write(js)
    S, cols = 140, 12; rows = (len(prev) + cols - 1) // cols; sh = Image.new('RGB', (cols * S, rows * S), (246, 247, 251)); dr = ImageDraw.Draw(sh)
    for i, (sid, im) in enumerate(prev):
        t = im.copy(); t.thumbnail((S - 8, S - 18)); sh.paste(t, ((i % cols) * S + 4, (i // cols) * S + 16), t); dr.text(((i % cols) * S + 4, (i // cols) * S + 2), sid, fill=(200, 40, 40))
    sh.save(os.path.join(D, 'preview.png')); print(len(out), 'ملصقاً', len(js) // 1024, 'KB')

if __name__ == '__main__': main()
